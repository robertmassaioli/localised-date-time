/**
 * Generates src/timezoneAbbreviations.js, the lookup that gives Luxon the tz-database
 * abbreviations (AEDT, EST, CET ...) that moment-timezone used to supply.
 *
 * Luxon takes zone names from Intl, which depends on the locale and the ICU version
 * (en-US prints "GMT+11" for Australia/Sydney). The macro always shows tz-database
 * abbreviations, so we ship the table instead of relying on Intl.
 *
 * moment-timezone is no longer a dependency of the app. To regenerate, install it
 * without saving it, run this script, then discard the install:
 *
 *   npm install --no-save moment-timezone
 *   node scripts/generate-tz-abbreviations.js
 *
 * The table covers 1970 onwards. For each zone it maps a UTC offset (minutes east of UTC)
 * to an abbreviation. When one offset has carried several abbreviations over time (for
 * example "MDT" and then "CST" at UTC-6), it maps to a list of [abbreviation, until] pairs
 * instead, where "until" is the end of that period in milliseconds since the epoch and the
 * last entry has no "until". Zones whose abbreviation is always numeric (such as "+04") are
 * left out because the formatter builds those from the offset.
 */
const fs = require('fs');
const path = require('path');
const moment = require('moment-timezone');

// Same rule as numericAbbreviation in src/dateTime.js
const numericAbbreviation = offset => {
  const hours = String(Math.floor(Math.abs(offset) / 60)).padStart(2, '0');
  const minutes = Math.abs(offset) % 60;
  return `${offset < 0 ? '-' : '+'}${hours}${minutes > 0 ? String(minutes).padStart(2, '0') : ''}`;
};

const SINCE = Date.UTC(1970, 0, 1);
const NUMERIC = /^[+-]/;
const table = {};

for (const name of moment.tz.names()) {
  const zone = moment.tz.zone(name);
  // offset (minutes east of UTC) -> [{ abbr, until }] in time order
  const periods = {};
  zone.untils.forEach((until, i) => {
    if (until <= SINCE) {
      return;
    }
    // moment stores offsets in minutes west of UTC, so flip the sign
    const offset = -zone.offsets[i];
    const list = (periods[offset] = periods[offset] ?? []);
    const last = list[list.length - 1];
    if (last && last.abbr === zone.abbrs[i]) {
      last.until = until;
    } else {
      list.push({ abbr: zone.abbrs[i], until });
    }
  });

  const entry = {};
  for (const [offset, list] of Object.entries(periods)) {
    if (list.length === 1) {
      // Numeric abbreviations only need an entry when they differ from the built-in form (the "-00" zones)
      if (!NUMERIC.test(list[0].abbr) || list[0].abbr !== numericAbbreviation(Number(offset))) {
        entry[offset] = list[0].abbr;
      }
    } else {
      entry[offset] = list.map((period, i) => (i === list.length - 1 ? period.abbr : [period.abbr, period.until]));
    }
  }
  if (Object.keys(entry).length > 0) {
    table[name] = entry;
  }
}

const render = value => (Array.isArray(value) ? `[${value.map(render).join(', ')}]` : typeof value === 'string' ? `'${value}'` : String(value));

const body = Object.keys(table).sort().map(name => {
  const offsets = Object.entries(table[name]).sort((a, b) => Number(b[0]) - Number(a[0]))
    .map(([offset, value]) => `'${offset}': ${render(value)}`).join(', ');
  return `  '${name}': { ${offsets} },`;
}).join('\n');

const header = `// Generated by scripts/generate-tz-abbreviations.js. Do not edit by hand.
// Maps an IANA zone to { UTC offset in minutes east: abbreviation }. An offset that carried
// several abbreviations maps to a list of [abbreviation, until in epoch milliseconds] pairs,
// ending with the abbreviation that applies from the last "until" onwards.
export const TimeZoneAbbreviations = {
`;
fs.writeFileSync(path.join(__dirname, '..', 'src', 'timezoneAbbreviations.js'), `${header}${body}\n};\n`);
console.log(`Wrote ${Object.keys(table).length} zones`);
